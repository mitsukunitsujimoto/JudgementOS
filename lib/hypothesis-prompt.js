/** モデルが旧表記で返した場合の正規化（仮説N: → 論点N:） */
export function normalizeRontenLabels(raw) {
  return String(raw || '')
    .replace(/\r\n/g, '\n')
    .replace(/仮説(\s*\d+\s*[:：])/g, '論点$1')
    .replace(/^仮説(\s*[:：])/gm, '論点$1');
}

